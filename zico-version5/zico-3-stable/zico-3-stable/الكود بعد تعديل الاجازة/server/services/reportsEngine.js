async function renderCSV(columns, rows, meta) {
  const BOM = "﻿";
  const escape = (v) => `"${String(v ?? "").replace(/"/g, '""')}"`;
  const headerRow = columns.map((c) => escape(c.header)).join(",");
  const dataRows = rows.map((row) => columns.map((col) => {
    const raw = getNestedValue(row, col.key);
    return escape(col.format ? fmtVal(raw, col.format) : (raw ?? ""));
  }).join(","));
  const metaRows = [
    `# ${BRANDING.footerText}`,
    `# Report: ${meta.title} | Generated: ${new Date(meta.generatedAt).toLocaleString("en-GB")} | By: ${meta.generatedBy} | Rows: ${meta.rowCount}`,
  ];
  return Buffer.from(BOM + [...metaRows, headerRow, ...dataRows].join("\n"), "utf-8");
}

