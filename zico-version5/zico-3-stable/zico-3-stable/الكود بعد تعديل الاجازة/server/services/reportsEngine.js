  High: { bg: "FFFEF3E2", fg: "FFE67E22", pdf: rgb(0.99, 0.95, 0.89), dot: rgb(0.9, 0.5, 0.13) },
  Medium: { bg: "FFFFF9E6", fg: "FFF1C40F", pdf: rgb(1, 0.98, 0.9), dot: rgb(0.95, 0.77, 0.06) },
