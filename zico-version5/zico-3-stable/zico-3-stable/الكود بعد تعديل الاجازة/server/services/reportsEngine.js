async function renderPDF(columns, rows, meta) {
  const pdfDoc = await PDFDocument.create();
  const font = await pdfDoc.embedFont(StandardFonts.Helvetica);
  const boldFont = await pdfDoc.embedFont(StandardFonts.HelveticaBold);

  const isWide = columns.length > 6;
  const pageW = isWide ? 1024 : 612;
  const pageH = isWide ? 612 : 792;
  const margin = isWide ? 30 : 40;
  const usableW = pageW - margin * 2;

  if (meta.isDashboard && columns.length <= 3) {
    await renderDashboardPDF(pdfDoc, columns, rows, meta, font, boldFont, pageW, pageH, margin, usableW);
  } else {
    await renderTablePDF(pdfDoc, columns, rows, meta, font, boldFont, pageW, pageH, margin, usableW, isWide);
  }

  return await pdfDoc.save();
}

async function renderDashboardPDF(pdfDoc, columns, rows, meta, font, boldFont, pageW, pageH, margin, usableW) {
  const page = pdfDoc.addPage([pageW, pageH]);
  let y = pageH - margin;

  // Executive masthead with a restrained, print-safe brand treatment.
  page.drawRectangle({ x: 0, y: pageH - 96, width: pageW, height: 96, color: DARK_BG });
  page.drawRectangle({ x: 0, y: pageH - 96, width: 8, height: 96, color: PRIMARY });

  if (BRANDING.logoPath) {
    try {
      const logoBytes = await readFileBytes(BRANDING.logoPath);
      const logo = await pdfDoc.embedPng(logoBytes);
      const scale = Math.min(0.34, 68 / logo.height);
      const dims = logo.scale(scale);
      page.drawImage(logo, { x: margin, y: pageH - 82, width: dims.width, height: dims.height });
    } catch { /* optional */ }
  }

  page.drawText("BOARD REPORT", { x: pageW - margin - 100, y: pageH - 38, size: 9, font: boldFont, color: PRIMARY });
  page.drawText("CONFIDENTIAL", { x: pageW - margin - 100, y: pageH - 55, size: 8, font, color: rgb(0.75, 0.75, 0.78) });
  y = pageH - 112;

  page.drawText(meta.title, { x: margin, y, size: 22, font: boldFont, color: rgb(0.1, 0.1, 0.1) });
  y -= 26;
  page.drawText("Executive decision support | current control and compliance posture", { x: margin, y, size: 8, font, color: rgb(0.42, 0.43, 0.46) });
  y -= 14;
  page.drawText(`${BRANDING.footerText} | ${new Date(meta.generatedAt).toLocaleString("en-GB")} | Prepared by: ${meta.generatedBy}`, { x: margin, y, size: 8, font, color: rgb(0.5, 0.5, 0.5) });
  y -= 8;
  page.drawLine({ start: { x: margin, y }, end: { x: pageW - margin, y }, thickness: 1.5, color: PRIMARY });
  y -= 30;

  // Watermark
  drawWatermark(page, font, pageW, pageH);

  // KPI bars
  const chartData = rows.map((r) => ({
    label: String(r[columns[0]?.key] || r.label || r.metric || r.name || Object.values(r)[0] || ""),
    value: parseFloat(r[columns[1]?.key] || r.value || r.score || r.percent || Object.values(r)[1]) || 0,
  })).filter((d) => d.label && !isNaN(d.value));

  if (chartData.length > 0) {
    const maxVal = Math.max(...chartData.map((d) => d.value), 1);
    const barH = 20;
    const barGap = 10;
    const labelW = 250;
    const barMaxW = usableW - labelW - 90;

    const average = Math.round(chartData.reduce((sum, item) => sum + item.value, 0) / chartData.length);
    const belowTarget = chartData.filter((item) => item.value < 80).length;
    const cardW = (usableW - 24) / 3;
    [["AVERAGE POSTURE", `${average}%`], ["FRAMEWORKS", String(chartData.length)], ["BELOW 80% TARGET", String(belowTarget)]].forEach(([label, value], index) => {
      const x = margin + index * (cardW + 12);
      page.drawRectangle({ x, y: y - 50, width: cardW, height: 50, color: index === 2 && belowTarget > 0 ? rgb(0.99, 0.96, 0.9) : rgb(0.96, 0.96, 0.97), borderColor: rgb(0.88, 0.88, 0.9), borderWidth: 0.7 });
      page.drawText(label, { x: x + 9, y: y - 15, size: 7, font: boldFont, color: rgb(0.42, 0.43, 0.46) });
      page.drawText(value, { x: x + 9, y: y - 37, size: 16, font: boldFont, color: index === 2 && belowTarget > 0 ? rgb(0.72, 0.37, 0.05) : rgb(0.08, 0.08, 0.1) });
    });
    y -= 64;
    page.drawText("POSTURE BY FRAMEWORK", { x: margin, y, size: 11, font: boldFont, color: rgb(0.1, 0.1, 0.1) });
    y -= 28;

    chartData.forEach((item) => {
      page.drawText(item.label.slice(0, 45), { x: margin, y: y - 4, size: 8, font, color: rgb(0.3, 0.3, 0.3) });
      page.drawRectangle({ x: margin + labelW, y: y - barH + 2, width: barMaxW, height: barH - 4, color: rgb(0.95, 0.95, 0.96) });
      page.drawRectangle({ x: margin + labelW, y: y - barH + 2, width: Math.max((item.value / maxVal) * barMaxW, 4), height: barH - 4, color: PRIMARY });
      page.drawText(String(item.value), { x: margin + labelW + barMaxW + 10, y: y - 4, size: 10, font: boldFont, color: PRIMARY });
      y -= barH + barGap;
    });
  }

  y -= 20;
  page.drawLine({ start: { x: margin, y }, end: { x: pageW - margin, y }, thickness: 0.5, color: rgb(0.85, 0.85, 0.85) });
  y -= 20;

  // Table
  const colW = usableW / columns.length;
  let x = margin;
  columns.forEach((col) => {
    page.drawRectangle({ x, y: y - 22, width: colW, height: 22, color: PRIMARY });
    page.drawText(col.header.slice(0, 40), { x: x + 4, y: y - 14, size: 7, font: boldFont, color: rgb(0.1, 0.1, 0.1) });
    x += colW;
  });
  y -= 22;

  const maxTableRows = Math.floor((y - margin - 30) / 14);
  rows.slice(0, maxTableRows).forEach((row, ri) => {
    x = margin;
    columns.forEach((col) => {
      const raw = getNestedValue(row, col.key);
      const text = (col.format ? fmtVal(raw, col.format) : String(raw ?? "—")).slice(0, 45);
      if (ri % 2 === 0) page.drawRectangle({ x, y: y - 14, width: colW, height: 14, color: rgb(0.98, 0.98, 0.99) });
      page.drawText(text, { x: x + 4, y: y - 9, size: 7, font, color: rgb(0.15, 0.15, 0.15) });
      x += colW;
    });
    y -= 14;
  });

  page.drawText(BRANDING.footerText, { x: margin, y: margin + 12, size: 7, font, color: rgb(0.5, 0.5, 0.5) });
  page.drawText("Page 1 of 1", { x: pageW - margin - 50, y: margin + 12, size: 7, font, color: rgb(0.5, 0.5, 0.5) });
}

async function renderTablePDF(pdfDoc, columns, rows, meta, font, boldFont, pageW, pageH, margin, usableW, isWide) {
  const fontSize = isWide ? 6 : 7;
  const headerH = isWide ? 24 : 28;
  const rowH = isWide ? 13 : 15;
  const colW = usableW / columns.length;
  const tableBottom = margin + (isWide ? 25 : 35);
  const headerBlockH = isWide ? 90 : 100;
  const tableTop = pageH - margin - headerBlockH;
  const rowsPerPage = Math.floor((tableTop - tableBottom) / rowH);

  let pageIndex = 0;
  let rowIndex = 0;

  while (rowIndex < rows.length || pageIndex === 0) {
    const page = pdfDoc.addPage([pageW, pageH]);
    let y = pageH - margin;

    // Header bar
    page.drawRectangle({ x: 0, y: pageH - 75, width: pageW, height: 75, color: rgb(0.98, 0.98, 0.99) });
    page.drawLine({ start: { x: 0, y: pageH - 75 }, end: { x: pageW, y: pageH - 75 }, thickness: 2.5, color: PRIMARY });

    if (BRANDING.logoPath) {
      try {
        const logoBytes = await readFileBytes(BRANDING.logoPath);
        const logo = await pdfDoc.embedPng(logoBytes);
        const scale = isWide ? 0.3 : 0.4;
        const dims = logo.scale(scale);
        page.drawImage(logo, { x: margin, y: pageH - margin - dims.height + 10, width: dims.width, height: dims.height });
      } catch { /* optional */ }
    }

    page.drawText("WADJET GRC", { x: pageW - margin - 110, y: pageH - margin - 8, size: isWide ? 12 : 16, font: boldFont, color: PRIMARY });
    y = pageH - 85;

    page.drawText(meta.title, { x: margin, y, size: isWide ? 16 : 20, font: boldFont, color: rgb(0.1, 0.1, 0.1) });
    y -= isWide ? 18 : 22;
    page.drawText(`${BRANDING.footerText} | ${new Date(meta.generatedAt).toLocaleString("en-GB")} | Prepared by: ${meta.generatedBy} | ${meta.rowCount} records`, { x: margin, y, size: isWide ? 6 : 8, font, color: rgb(0.5, 0.5, 0.5) });
    y -= 6;
    page.drawLine({ start: { x: margin, y }, end: { x: pageW - margin, y }, thickness: 1, color: PRIMARY });
    y -= 10;

    // Watermark
    drawWatermark(page, font, pageW, pageH);

    // Header row
    let x = margin;
    columns.forEach((col) => {
      page.drawRectangle({ x, y: y - headerH, width: colW, height: headerH, color: PRIMARY });
      page.drawText(col.header.slice(0, 45), { x: x + 3, y: y - headerH + 7, size: fontSize, font: boldFont, color: rgb(0.1, 0.1, 0.1) });
      x += colW;
    });
    y -= headerH;

    // Data rows
    const pageRows = rows.slice(rowIndex, rowIndex + rowsPerPage);
    pageRows.forEach((row, ri) => {
      x = margin;
      columns.forEach((col, ci) => {
        const raw = getNestedValue(row, col.key);
        const text = (col.format ? fmtVal(raw, col.format) : String(raw ?? "—")).slice(0, 50);
        const isColorCol = meta.colorColumns.includes(col.key);
        if (isColorCol) {
          const style = getRiskStyle(raw);
          page.drawRectangle({ x, y: y - rowH, width: colW, height: rowH, color: style.pdf });
        } else if (ri % 2 === 0) {
          page.drawRectangle({ x, y: y - rowH, width: colW, height: rowH, color: rgb(0.98, 0.98, 0.99) });
        }
        page.drawText(text, { x: x + 3, y: y - 9, size: fontSize, font, color: rgb(0.15, 0.15, 0.15) });
        x += colW;
      });
      y -= rowH;
      rowIndex++;
    });

    const totalPages = Math.max(1, Math.ceil(rows.length / rowsPerPage));
    page.drawText(BRANDING.footerText, { x: margin, y: margin + 10, size: 7, font, color: rgb(0.5, 0.5, 0.5) });
    page.drawText(`Page ${pageIndex + 1} of ${totalPages}`, { x: pageW - margin - 60, y: margin + 10, size: 7, font, color: rgb(0.5, 0.5, 0.5) });

    if (rowIndex >= rows.length) break;
    pageIndex++;
  }
}

function drawWatermark(page, font, pageW, pageH) {
  const text = BRANDING.watermarkText;
  const fontSize = pageW > 700 ? 46 : 56;
  const textWidth = font.widthOfTextAtSize(text, fontSize);
  page.drawText(text, {
    x: pageW / 2 - textWidth / 2, y: pageH / 2 + 70, size: fontSize, font, color: PRIMARY, opacity: 0.06, rotate: degrees(45),
  });
}

