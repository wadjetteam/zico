async function renderXLSX(columns, rows, meta) {
  const wb = new ExcelJS.Workbook();
  wb.creator = "WADJET GRC Platform";
  wb.created = new Date();
  const ws = wb.addWorksheet(meta.title.slice(0, 31));

  // Logo
  if (BRANDING.logoPath) {
    try {
      const ext = BRANDING.logoPath.toLowerCase().endsWith(".png") ? "png" : "jpeg";
      const logoId = wb.addImage({ filename: BRANDING.logoPath, extension: ext });
      ws.addImage(logoId, { tl: { col: 0, row: 0 }, ext: { width: 200, height: 60 } });
    } catch { /* optional */ }
  }

  // Title
  const titleRow = 5;
  ws.mergeCells(titleRow, 1, titleRow, Math.max(columns.length, 8));
  const titleCell = ws.getCell(titleRow, 1);
  titleCell.value = meta.title;
  titleCell.font = { size: 20, bold: true, color: { argb: "FF1A1A1A" }, name: "Calibri" };
  titleCell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FFFFFFFF" } };
  titleCell.alignment = { horizontal: "left", vertical: "middle" };
  ws.getRow(titleRow).height = 35;

  // Subtitle
  const subRow = titleRow + 1;
  ws.mergeCells(subRow, 1, subRow, Math.max(columns.length, 8));
  const subCell = ws.getCell(subRow, 1);
  subCell.value = `${BRANDING.footerText} | ${new Date(meta.generatedAt).toLocaleString("en-GB")} | Prepared by: ${meta.generatedBy} | ${meta.rowCount} records`;
  subCell.font = { size: 9, italic: true, color: { argb: "FF888888" }, name: "Calibri" };
  subCell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FFFFFFFF" } };

  // Dashboard KPI cards
  if (meta.isDashboard && rows.length > 0 && columns.length <= 3) {
    const kpiStart = subRow + 2;
    rows.forEach((row, i) => {
      const key = String(row[columns[0]?.key] || row.label || row.metric || row.name || Object.values(row)[0] || "");
      const val = String(row[columns[1]?.key] || row.value || row.score || row.percent || Object.values(row)[1] || "");
      const labelCell = ws.getCell(kpiStart + i, 1);
      labelCell.value = key;
      labelCell.font = { size: 11, bold: true, color: { argb: "FF2C3E50" }, name: "Calibri" };
      labelCell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FFF8F9FA" } };
      labelCell.border = { bottom: { style: "thin", color: { argb: "FFDEE2E6" } } };
      const valCell = ws.getCell(kpiStart + i, 2);
      valCell.value = val;
      valCell.font = { size: 16, bold: true, color: { argb: `FF${PRIMARY_HEX}` }, name: "Calibri" };
      valCell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FFF8F9FA" } };
      valCell.alignment = { horizontal: "right" };
      valCell.border = { bottom: { style: "thin", color: { argb: "FFDEE2E6" } } };
    });
    ws.getColumn(1).width = 50;
    ws.getColumn(2).width = 20;
  }

  const tableStart = meta.isDashboard && rows.length > 0 && columns.length <= 3
    ? subRow + 2 + rows.length + 2
    : subRow + 2;

  // Header
  const headerRow = ws.getRow(tableStart);
  columns.forEach((col, i) => {
    const cell = headerRow.getCell(i + 1);
    cell.value = col.header;
    cell.font = { bold: true, color: { argb: "FF1A1A1A" }, size: 10, name: "Calibri" };
    cell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: `FF${PRIMARY_HEX}` } };
    cell.alignment = { horizontal: "center", vertical: "middle", wrapText: true };
    cell.border = { bottom: { style: "medium", color: { argb: "FFB8860B" } }, top: { style: "thin", color: { argb: "FFDEE2E6" } }, left: { style: "thin", color: { argb: "FFDEE2E6" } }, right: { style: "thin", color: { argb: "FFDEE2E6" } } };
  });
  ws.getRow(tableStart).height = 28;

  // Data rows
  rows.forEach((row, ri) => {
    const excelRow = ws.getRow(tableStart + 1 + ri);
    excelRow.height = 20;
    const fillColor = ri % 2 === 0 ? "FFFFFFFF" : "FFF8F9FA";
    columns.forEach((col, ci) => {
      const raw = getNestedValue(row, col.key);
      const cell = excelRow.getCell(ci + 1);
      cell.value = col.format ? fmtVal(raw, col.format) : (raw ?? "—");
      cell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: fillColor } };
      cell.font = { color: { argb: "FF2C3E50" }, size: 9, name: "Calibri" };
      cell.alignment = { vertical: "middle", wrapText: true };
      cell.border = { bottom: { style: "thin", color: { argb: "FFEBEEF0" } }, left: { style: "thin", color: { argb: "FFEBEEF0" } }, right: { style: "thin", color: { argb: "FFEBEEF0" } } };
      if (meta.colorColumns.includes(col.key)) {
        const style = getRiskStyle(raw);
        cell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: style.bg } };
        cell.font = { color: { argb: style.fg }, size: 9, bold: true, name: "Calibri" };
      }
    });
  });

  // Auto-width
  columns.forEach((col, i) => {
    let maxLen = String(col.header).length + 3;
    for (let ri = 0; ri < Math.min(rows.length, 200); ri++) {
      const raw = getNestedValue(rows[ri], col.key);
      const val = col.format ? fmtVal(raw, col.format) : String(raw ?? "");
      maxLen = Math.max(maxLen, val.length + 3);
    }
    ws.getColumn(i + 1).width = Math.min(Math.max(maxLen, 12), 55);
  });

  ws.views = [{ state: "frozen", ySplit: tableStart }];

  // Watermark
  if (rows.length > 0) {
    const wmRow = tableStart + Math.min(rows.length, 10) + 3;
    ws.mergeCells(wmRow, 1, wmRow, Math.max(columns.length, 8));
    const wmCell = ws.getCell(wmRow, 1);
    wmCell.value = BRANDING.watermarkText;
    wmCell.font = { size: 36, color: { argb: "FFF0F0F0" }, italic: true, name: "Calibri" };
    wmCell.alignment = { horizontal: "center", vertical: "middle" };
  }

  return await wb.xlsx.writeBuffer();
}

